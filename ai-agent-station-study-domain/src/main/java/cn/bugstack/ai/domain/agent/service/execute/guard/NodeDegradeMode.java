package cn.bugstack.ai.domain.agent.service.execute.guard;

/**
 * 节点失败后的降级策略
 * <p>
 * 之所以要分档而不是「统一 catch 后返回错误文案」：本项目各节点在链路里的地位完全不同，
 * 一刀切的结果只有两种糟糕形态 ——
 * 「所有失败都中断链路」（监督/总结这类锦上添花的节点失败会毁掉已经拿到的有效结果）
 * 「所有失败都吞掉继续」（规划失败后续节点拿着空 stepMap 空转，用户完全不知道发生了什么）。
 */
public enum NodeDegradeMode {

    /**
     * 不可降级：重试耗尽后抛出 {@link NodeGuardException}，快速失败并中断链路。
     * 适用：产出是下游唯一输入的节点（如 Flow 的规划节点）。
     */
    FAIL_FAST,

    /**
     * 降级到兜底值：重试耗尽后使用 {@code fallback} 的产出继续。
     * 适用：丢了不影响主流程，但下游仍需要某种形式的输入（如工具分析、质量监督）。
     */
    FALLBACK,

    /**
     * 跳过：重试耗尽后返回 null，由调用方跳过本节点的后续处理。
     * 适用：纯展示/总结环节（如最终报告生成）。
     */
    SKIP
}
